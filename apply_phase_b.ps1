if ($Files.Count -ne 13) { throw 'Internal error: the script must contain exactly 13 files.' }

# --- 3. Check everything BEFORE writing anything ---------------------------------------------------
$plan = @()
$problems = @()
foreach ($f in $Files) {
    $bytes = Expand-Blob $f.Data
    if ((Get-Sha256Hex $bytes) -ne $f.After) { $problems += "$($f.Path): embedded content is damaged (hash mismatch); re-download the script"; continue }
    $full = Join-Path $Root $f.Path
    $action = 'CREATED'
    if (Test-Path -LiteralPath $full) {
        $current = Get-LfSha256 $full
        if ($current -eq $f.After) { $action = 'UNCHANGED (already applied)' }
        elseif ($f.Kind -eq 'MODIFIED' -and $current -eq $f.Before) { $action = 'OVERWRITTEN' }
        elseif ($Force) { $action = 'OVERWRITTEN (-Force)' }
        else { $problems += "$($f.Path): your copy differs from the version Phase B was built on; not overwriting (use -Force to override)" }
    } elseif ($f.Kind -eq 'MODIFIED') {
        $problems += "$($f.Path): expected an existing file but it is missing"
    }
    $plan += [pscustomobject]@{ File = $f; Full = $full; Bytes = $bytes; Action = $action }
}
if ($problems.Count -gt 0) {
    Write-Host 'Phase B was NOT applied. Nothing was written:' -ForegroundColor Red
    $problems | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    exit 1
}

# --- 4. Write exactly the 13 files ----------------------------------------------------------------
$results = @()
foreach ($item in $plan) {
    $dir = Split-Path -Parent $item.Full
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    if ($item.Action -ne 'UNCHANGED (already applied)') { [System.IO.File]::WriteAllBytes($item.Full, $item.Bytes) }
    $written = Get-Sha256Hex ([System.IO.File]::ReadAllBytes($item.Full))
    if ($item.Action -eq 'UNCHANGED (already applied)') { $written = Get-LfSha256 $item.Full }
    if ($written -ne $item.File.After) { throw "Verification failed after writing $($item.File.Path)" }
    $results += [pscustomobject]@{ Path = $item.File.Path; Action = $item.Action; SHA256 = $written }
}

# --- 5. Report ----------------------------------------------------------------------------------
$results | Format-Table -AutoSize Path, Action, SHA256 | Out-String -Width 250 | Write-Host
Write-Host 'Phase B files applied. No migration, test, build, or server command was executed.' -ForegroundColor Green
