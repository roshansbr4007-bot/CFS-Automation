# --- 3. Check everything BEFORE writing anything ---------------------------------------------------
$plan = @(); $problems = @()
foreach ($f in $Files) {
    $bytes = Expand-Blob $f.Data
    if ((Get-Sha256Hex $bytes) -ne $f.After) { $problems += "$($f.Path): embedded content is damaged (hash mismatch); re-download the script"; continue }
    $full = Join-Path $Root $f.Path
    $action = 'CREATED'
    if (Test-Path -LiteralPath $full) {
        $current = Get-LfSha256 $full
        if ($current -eq $f.After) { $action = 'UNCHANGED (already applied)' }
        elseif ($f.Kind -eq 'MODIFIED' -and $current -eq $f.Before) { $action = 'OVERWRITTEN' }
        elseif ($Force) { $action = 'OVERWRITTEN (-Force)' }
        else { $problems += "$($f.Path): your copy differs from the version this change was built on; not overwriting (use -Force only after review)" }
    } elseif ($f.Kind -eq 'MODIFIED') {
        $problems += "$($f.Path): expected an existing file but it is missing"
    }
    $plan += [pscustomobject]@{ File = $f; Full = $full; Bytes = $bytes; Action = $action }
}
if ($problems.Count -gt 0) {
    Write-Host 'The Responsibility Deadline change was NOT applied. Nothing was written:' -ForegroundColor Red
    $problems | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    exit 1
}

# --- 4. Write exactly these files and verify each one ------------------------------------------------
$results = @()
foreach ($item in $plan) {
    $dir = Split-Path -Parent $item.Full
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
