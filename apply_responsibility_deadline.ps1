<#
  apply_responsibility_deadline.ps1 - applies the Responsibility Deadline (SLA) change to the CFS project.
  Run it FROM THE PROJECT ROOT (the folder containing backend\ and frontend\):

      powershell -ExecutionPolicy Bypass -File .\apply_responsibility_deadline.ps1

  Writes exactly 9 files and nothing else. Runs no migration, test, build, server or git command,
  and deletes nothing. Nothing is written unless every check passes first:
   - each embedded file must match its SHA-256 (a damaged download is refused);
   - each MODIFIED file must currently be the version this change was built on (line endings ignored)
     or already the new version; otherwise it stops so local changes are never overwritten;
   - each CREATED file must not exist, or already be the new version;
   - Phase B migration 0004 must be present and no other recurring 0005_* migration may exist.
  -Force overrides ONLY the 'your copy differs' checks. Every write is verified by SHA-256 afterwards.
#>
[CmdletBinding()]
param([switch]$Force)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$Root = (Get-Location).Path

function Get-Sha256Hex([byte[]]$Bytes) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { return ([System.BitConverter]::ToString($sha.ComputeHash($Bytes))).Replace('-', '').ToLowerInvariant() }
    finally { $sha.Dispose() }
}
# Hash with CRLF turned into LF, so a Git CRLF checkout of an unchanged file still matches.
function Get-LfSha256([string]$FullPath) {
    $text = [System.Text.Encoding]::UTF8.GetString([System.IO.File]::ReadAllBytes($FullPath))
    $text = $text.Replace("`r`n", "`n")
    return Get-Sha256Hex ((New-Object System.Text.UTF8Encoding($false)).GetBytes($text))
}
function Expand-Blob([string]$Base64) {
    $compressed = [System.Convert]::FromBase64String(($Base64 -replace '\s', ''))
    $source = New-Object System.IO.MemoryStream(,$compressed)
    $gzip = New-Object System.IO.Compression.GZipStream($source, [System.IO.Compression.CompressionMode]::Decompress)
    $output = New-Object System.IO.MemoryStream
    try { $gzip.CopyTo($output) } finally { $gzip.Dispose(); $source.Dispose() }
    return ,$output.ToArray()
}

